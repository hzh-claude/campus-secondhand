//      这里跟着改成同一个接口。两处都落成 wx.chooseMedia 后，
//      文案里的描述和代码里的调用又能一一对上了 —— 这正是审核在看的东西。
//   ⚠️ chat.js 那一行是后来补的。这一段自称「全项目检索确认」，但它之前
//      只列了 edit 和 suggest 两处，漏了聊天发图 —— 而正文里「相册 / 相机」
//      那一节也跟着漏了。这种漏报很危险：审核要求隐私说明和实际调用的
//      敏感接口一一对应，少写一处就是被打回的理由。
//      改这一页时不要只信这张单子，去 grep 一遍 wx.chooseMedia / GetLocation
//      之类的关键字再核一次。
//   全项目【没有】用到：wx.getUserProfile / wx.getUserInfo（不拉微信头像昵称）、
//   wx.getPhoneNumber（不取微信绑定手机号）、wx.login（不用 code 换登录态）。
//   身份来自云开发的 getWXContext，用户资料全部由用户自己在编辑页手填。
