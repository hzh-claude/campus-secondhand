//   内容必须和代码里实际用到的接口一一对上 ——
//   写了没做的，或者做了没写的，审核都会打回来。
//
// 【核对方法】
//   文案里的每一条都对应代码里的一处调用，改功能时请同步改这里。
//   当前实际用到的敏感接口（全项目检索确认）：
//     wx.getFuzzyLocation  → utils/location.js（注册时确认是否在校内）
//     wx.chooseMedia       → pages/edit/edit.js（换头像）
//                          → pages/suggest/suggest.js（意见反馈附图）
//                          → pages/chat/chat.js（聊天发图）
//   ⚠️ 意见反馈这一条原来写的是 wx.chooseImage，并注明「已废弃的旧接口」。
