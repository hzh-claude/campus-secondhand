// utils/goods-refresh.js
//
// 「在售商品池变了」这个信号，用来跨页面传递。
//
// ============================================================
// 【为什么需要它】
// ============================================================
//   首页、分类页、卖家主页、搜索页都是【只读列表】，它们的查询条件里都带着
//   status = on_sale。当一件商品在别的页面被买走 / 卖掉 / 下架，它就从
//   这个池子里出去了 —— 但这四个页面自己不知道。
//
//   表现是：用户下单买走一件商品 → 返回列表 → 那件商品还挂在架上、还能点，
//   点进去才发现已经买不了了。列表本身并没有错，只是没人告诉它要重查。
//
// ============================================================
// 【为什么不用 onShow 无条件重查】
// ============================================================
//   这四个页面都分页。而「在列表里翻半天 → 点进详情看一眼 → 退回来」
//   是极常见的动作。如果每次 onShow 都重置分页重查，那个「退回来」
//   会把列表打回第一页 —— 滚动位置、翻过的几页，全没了。
//
//   那是在修一个「偶尔看到脏数据」的时候，顺手制造一个「每次都丢位置」。
//   代价比它要修的 bug 还大。
//
//   所以反过来做：只有在【真的改了】的时候留一个标记，页面下次显示时
//   消费掉它。没改过就什么都不做 —— 一次多余的查询都不发。
//
// ============================================================
// 【producers —— 谁改动了在售池，谁就要调 markGoodsChanged()】
// ============================================================
//   pages/push/push.js         发布 / 编辑商品成功后
//   pages/my_push/my_push.js   上架 / 下架 / 删除成功后
//   pages/detail/detail.js     下单成功后（商品变 locked，别人不能再买）
//   pages/my_sold/my_sold.js   确认卖出 / 拒绝 / 撤销卖出后
//   pages/my_buy/my_buy.js     取消订单后（商品回到 on_sale）
//
//   ⚠️【加了新的、会改动商品状态的入口，记得回来在这一段补一行】
//      漏掉不会报错，只会让列表悄悄停在旧数据上 —— 正是这个文件要修的毛病。
//
// ============================================================
// 【consumers —— 谁在 onShow 里消费它】
// ============================================================
//   pages/home/home.js
//   pages/type_list/type_list.js
//   pages/seller/seller.js
//   pages/search/search.js
//
// 【为什么用本地缓存传，不写进 globalData】
//   这几个页面之间有 navigateTo / navigateBack / switchTab 各种组合，
//   而写标记的页面和读标记的页面不总是同一个栈上的。storage 不关心
//   页面栈怎么走，什么时候都能读到。
//   这里存的是一个「用完即弃的标记」，不是数据 —— 丢了只是列表晚一次刷新，
//   不会损坏任何东西（settings.js 的「清除缓存」那一段也是这么说的）。

const KEY = 'needRefreshGoods';

// 标记「在售池变了」。下一个显示的列表页会消费掉它。
function markGoodsChanged() {
  wx.setStorageSync(KEY, true);
}

// 【读取即消费】—— 读到就顺手清掉。
//   不清的话，一次下单会让此后每次进首页都重置一次列表，
//   直到用户手动清缓存为止。
function consumeGoodsChanged() {
  if (!wx.getStorageSync(KEY)) return false;
  wx.removeStorageSync(KEY);
  return true;
}

module.exports = { markGoodsChanged, consumeGoodsChanged };
